using ExamPlatform.Domain.Enums;

namespace ExamPlatform.Domain.Entities
{
    // Maps to "payments". Every simulated charge attempt, successful or not —
    // this is the audit trail admin's Revenue Dashboard and failure analytics
    // read from. Never deleted or overwritten after the outcome is recorded;
    // only Status/CompletedAt/FailureReason are set once the fake gateway responds.
    public class Payment
    {
        public int PaymentId { get; set; }              // PK

        public int UserId { get; set; }                  // FK -> User (payer)

        // Set only when Purpose is subscription-related; null for exam purchases.
        public int? SubscriptionId { get; set; }         // FK -> ExaminerSubscription

        public PaymentPurpose Purpose { get; set; }

        // SERVER-COMPUTED at charge time from Exam.Price / SubscriptionPlan
        // price — never trusted from the client (Part 9 security requirement).
        public decimal Amount { get; set; }
        public string Currency { get; set; } = "INR";

        public PaymentMethod Method { get; set; }
        public PaymentStatus Status { get; set; }

        // Fake identifiers, generated by PaymentGatewayService — never real.
        public string FakeTransactionId { get; set; } = null!;   // unique
        public string FakeGatewayReference { get; set; } = null!;

        // Client-generated once per checkout attempt; a retry with the same
        // key returns the original outcome instead of charging twice.
        public string IdempotencyKey { get; set; } = null!;      // unique

        public int? CouponId { get; set; }               // FK -> Coupon, nullable

        public DateTime InitiatedAt { get; set; }
        public DateTime? CompletedAt { get; set; }
        public string? FailureReason { get; set; }

        public User User { get; set; } = null!;
        public ExaminerSubscription? Subscription { get; set; }
        public Coupon? Coupon { get; set; }
        public Invoice? Invoice { get; set; }
        public CandidatePurchase? CandidatePurchase { get; set; }
    }
}
